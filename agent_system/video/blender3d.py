# -*- coding: utf-8 -*-
"""video/blender3d.py — 3D Animation backend (Blender integration boundary).

**Blender is not installed on this machine.** This module therefore does two
honest things:

1. It reports unavailability with a precise, actionable error instead of
   pretending a 3D render happened.
2. It generates a real Blender (``bpy``) scene script from the same validated
   render spec, so that the moment Blender is installed the backend can render
   — plus it encodes the resulting PNG sequence with ffmpeg.

Nothing in this file claims a 3D output exists unless Blender actually ran.
"""
import json
import os
import shutil
import subprocess
from typing import Any, Callable, Dict, List, Optional

from . import common
from .spec import RenderSpec

INSTALL_STEPS = [
    "Option A (Homebrew):  brew install --cask blender",
    "Option B (download):  https://www.blender.org/download/  → Blender 4.x for macOS",
    "Verify:               blender --version",
    "Then re-run the job with style=blender3d.",
]

LIMITATIONS = [
    "Blender is a large, separately-installed application and is NOT bundled here.",
    "3D output is only produced when a working `blender` binary is on PATH.",
    "The generated bpy script renders an animated 3D logo/emblem + title plates; "
    "bespoke 3D models (buildings, characters) are not included and must be authored.",
    "Render time for 3D is significantly higher than 2D backends.",
]


def blender_binary() -> Optional[str]:
    return shutil.which("blender")


def blender_available() -> bool:
    return blender_binary() is not None


def blender_version() -> Optional[str]:
    b = blender_binary()
    if not b:
        return None
    try:
        proc = subprocess.run([b, "--version"], capture_output=True, text=True, timeout=60)
        line = (proc.stdout or proc.stderr or "").strip().splitlines()
        return line[0] if line else "present"
    except Exception:
        return "present"


def availability() -> Dict[str, Any]:
    return {
        "style": "blender3d",
        "available": blender_available(),
        "binary": blender_binary(),
        "version": blender_version(),
        "install_steps": INSTALL_STEPS if not blender_available() else [],
    }


# ---------------------------------------------------------------- bpy script
def write_blender_script(spec: RenderSpec, path: str, frames_dir: str) -> str:
    """Generate a real Blender script that renders the film's scenes to PNGs."""
    scenes = [{"id": s["id"], "dur": s["dur"], "heading": s["heading"],
               "sub": s["sub"], "kind": s["kind"]} for s in spec.scenes]
    script = BLENDER_TEMPLATE % {
        "width": spec.width, "height": spec.height, "fps": spec.fps,
        "scenes_json": json.dumps(scenes, ensure_ascii=False),
        "frames_dir": frames_dir.replace("\\", "/"),
        "total": round(spec.total_duration, 3),
        "firm": spec.firm_name.encode("unicode_escape").decode("ascii"),
    }
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(script)
    return path


BLENDER_TEMPLATE = '''# -*- coding: utf-8 -*-
# Auto-generated by agent_system.video.blender3d — 3D Animation backend.
# Renders an animated 3D emblem + per-scene title plates to a PNG sequence.
import bpy, json, math, os, sys

W, H = %(width)d, %(height)d
FPS = %(fps)d
SCENES = json.loads(r"""%(scenes_json)s""")
OUT = r"%(frames_dir)s"
FIRM = bytes(r"%(firm)s", "ascii").decode("unicode_escape")

def clean():
    bpy.ops.wm.read_factory_settings(use_empty=True)

def setup_scene():
    sc = bpy.context.scene
    sc.render.resolution_x = W
    sc.render.resolution_y = H
    sc.render.resolution_percentage = 100
    sc.render.image_settings.file_format = "PNG"
    sc.render.fps = FPS
    sc.render.film_transparent = False
    world = bpy.data.worlds.new("World")
    sc.world = world
    world.use_nodes = True
    bg = world.node_tree.nodes["Background"]
    bg.inputs[0].default_value = (0.031, 0.106, 0.149, 1.0)  # brand navy
    bg.inputs[1].default_value = 0.6
    return sc

def add_camera():
    cam_data = bpy.data.cameras.new("Cam")
    cam = bpy.data.objects.new("Cam", cam_data)
    bpy.context.collection.objects.link(cam)
    cam.location = (0, -6.2, 1.6)
    cam.rotation_euler = (math.radians(78), 0, 0)
    bpy.context.scene.camera = cam
    return cam

def add_light():
    ld = bpy.data.lights.new("Key", type="AREA")
    ld.energy = 900
    ld.size = 6
    lo = bpy.data.objects.new("Key", ld)
    lo.location = (3.2, -4.0, 4.5)
    lo.rotation_euler = (math.radians(55), 0, math.radians(35))
    bpy.context.collection.objects.link(lo)
    gold = bpy.data.lights.new("Rim", type="POINT")
    gold.energy = 300
    gold.color = (0.79, 0.66, 0.43)
    go = bpy.data.objects.new("Rim", gold)
    go.location = (-3.0, 2.0, 2.0)
    bpy.context.collection.objects.link(go)

def add_text(body, size=1.0, z=0.0, color=(0.97, 0.965, 0.945, 1.0)):
    bpy.ops.object.text_add(location=(0, 0, z))
    ob = bpy.context.object
    ob.data.body = body
    ob.data.align_x = "CENTER"
    ob.data.align_y = "CENTER"
    ob.data.size = size
    mat = bpy.data.materials.new("Txt")
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    if bsdf:
        bsdf.inputs[0].default_value = color
        bsdf.inputs["Roughness"].default_value = 0.35
    ob.data.materials.append(mat)
    return ob

def add_emblem():
    bpy.ops.mesh.primitive_torus_add(major_radius=1.35, minor_radius=0.075,
                                     location=(0, 0, 0))
    ring = bpy.context.object
    mat = bpy.data.materials.new("Gold")
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    if bsdf:
        bsdf.inputs[0].default_value = (0.79, 0.66, 0.43, 1.0)
        bsdf.inputs["Metallic"].default_value = 1.0
        bsdf.inputs["Roughness"].default_value = 0.25
    ring.data.materials.append(mat)
    return ring

def animate(obj, scene_dur, spin=True):
    obj.rotation_euler = (0, 0, 0)
    obj.keyframe_insert("rotation_euler", frame=1)
    if spin:
        obj.rotation_euler = (0, 0, math.radians(360 * 0.25))
        obj.keyframe_insert("rotation_euler", frame=int(scene_dur * FPS))

def render_frames(scene_name, count, tag):
    sc = bpy.context.scene
    sc.frame_start = 1
    sc.frame_end = max(2, count)
    sc.render.filepath = os.path.join(OUT, tag + "_")
    bpy.ops.render.render(animation=True)

def main():
    clean()
    setup_scene()
    add_camera()
    add_light()
    os.makedirs(OUT, exist_ok=True)
    for i, s in enumerate(SCENES):
        clean()
        setup_scene()
        add_camera()
        add_light()
        dur = float(s.get("dur", 4.0))
        tag = s.get("id") or ("sc%%d" %% i)
        heading = (s.get("heading") or "").strip()
        if s.get("kind") in ("endcard", "title"):
            emblem = add_emblem()
            animate(emblem, dur)
            if heading:
                add_text(heading[:40], size=0.34, z=-1.9,
                         color=(0.031, 0.106, 0.149, 1.0))
        else:
            if heading:
                add_text(heading[:60], size=0.30, z=0.0)
        render_frames(heading, int(round(dur * FPS)), tag)
        print("SCENE_DONE", tag)

main()
'''


# ---------------------------------------------------------------- backend
class Blender3DBackend(object):
    style = "blender3d"
    label = "3D Animation (Blender)"

    def available(self) -> bool:
        return blender_available()

    def render(self, spec: RenderSpec, out_path: str, work_dir: str,
               asset_dir: str = "", cancel: Optional[Callable[[], bool]] = None,
               progress: Optional[Callable[[str, int], None]] = None) -> Dict[str, Any]:
        os.makedirs(work_dir, exist_ok=True)
        blender = blender_binary()
        if not blender:
            # Honest failure: we generate the script so the work is not lost,
            # then raise so the caller reports the real blocker.
            script = write_blender_script(spec, os.path.join(work_dir, "scene_3d.py"),
                                          os.path.join(work_dir, "blender_frames"))
            raise common.RenderError(
                "3D backend unavailable: Blender is not installed on this machine. "
                "A ready-to-run Blender script was written to %s. To enable 3D: %s"
                % (script, " | ".join(INSTALL_STEPS)))

        if not common.ffmpeg_available():
            raise common.RenderError("ffmpeg is required to encode the 3D PNG sequence")

        script = write_blender_script(spec, os.path.join(work_dir, "scene_3d.py"),
                                      os.path.join(work_dir, "blender_frames"))
        if progress:
            progress("running Blender (background) — this is the slow path", 5)
        proc = common.run([blender, "--background", "--factory-startup",
                           "--python", script], timeout=max(900, int(spec.total_duration * 120)))
        if proc.returncode != 0:
            raise common.RenderError("Blender failed: %s"
                                     % proc.stderr.decode("utf-8", "ignore")[-800:])

        frames_dir = os.path.join(work_dir, "blender_frames")
        pngs = sorted(f for f in os.listdir(frames_dir) if f.endswith(".png")) \
            if os.path.isdir(frames_dir) else []
        if not pngs:
            raise common.RenderError("Blender produced no frames in %s" % frames_dir)

        # count check: assemble the PNG sequence with ffmpeg
        video_only = os.path.join(work_dir, "_video_only.mp4")
        common.run([common.FFMPEG, "-y", "-hide_banner", "-loglevel", "error",
                    "-framerate", str(spec.fps), "-pattern_type", "glob",
                    "-i", os.path.join(frames_dir, "*.png"),
                    "-c:v", "libx264", "-preset", "medium", "-crf", "18",
                    "-pix_fmt", "yuv420p", video_only], timeout=1800)
        audio_path, audio_meta = common.build_audio_track(
            os.path.join(work_dir, "_audio.wav"), spec.total_duration, spec.audio, work_dir)
        common.mux(video_only, audio_path, out_path)
        validation = common.validate_mp4(out_path, spec.width, spec.height, spec.fps)
        manifest = common.write_render_manifest(
            os.path.join(work_dir, "render_manifest.json"), spec, self.style,
            {"name": "blender-ffmpeg", "blender": blender_version(),
             "frames": len(pngs)},
            limitations=LIMITATIONS, validation=validation,
            extra={"audio_detail": audio_meta, "blender_script": script})
        return {"output": out_path, "manifest": manifest, "validation": validation}


def render(spec: RenderSpec, out_path: str, work_dir: str, asset_dir: str = "",
           cancel: Optional[Callable[[], bool]] = None,
           progress: Optional[Callable[[str, int], None]] = None) -> Dict[str, Any]:
    return Blender3DBackend().render(spec, out_path, work_dir, asset_dir, cancel, progress)
